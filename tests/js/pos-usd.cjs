const assert = require('node:assert/strict');
const vm = require('node:vm');
const html = require('node:fs').readFileSync(0, 'utf8');
const script = [...html.matchAll(/<script[^>]*>([\s\S]*?)<\/script>/g)].map(m => m[1]).find(s => s.includes("Alpine.data('posTerminal'"));
assert.ok(script);
let factory;
vm.runInNewContext(script, { document: { addEventListener: (_, fn) => fn() }, Alpine: { data: (_, fn) => { factory = fn; } }, console });
const pos = factory();
pos.$nextTick = () => {};
pos.$refs = {};
pos.cart = [{ id: 1, quantity: 1, sale_price: 8000, tax_rate: 0, _discount: 0, _unitPrice: '' }];
const cash = pos.paymentMethods.find(m => m.type === 'cash');
let focused = 0, selected = 0;
pos.$refs.receivedCrc = { focus() { focused++; }, select() { selected++; } };
pos.$refs.receivedAmount = { focus() { throw new Error('Hidden CRC input focused'); } };
pos.$nextTick = fn => fn();
pos.checkout.draft.amount = '8000';
pos.selectPaymentMethod(cash);
assert.equal(focused, 1);
assert.equal(selected, 1);
assert.match(html, /x-ref="receivedCrc"/);
assert.match(html, /@input="updateCashReceived\('CRC', \$event.target.value\)"/);
assert.match(html, /@input="updateCashReceived\('USD', \$event.target.value\)"/);
pos.updateCashReceived('USD', '20');
assert.equal(pos.checkout.draft.receivedAmount, '');
assert.equal(pos.usdDraft.covered, '10100.0000');
pos.updateCashReceived('CRC', '9000');
assert.equal(pos.checkout.draft.receivedUsd, '');
assert.equal(pos.usdDraft.covered, '9000.0000');
assert.equal(pos.usdDraft.equivalent, '0.0000');
assert.equal(pos.usdDraft.changeCrc, '1000.0000');
pos.updateCashReceived('USD', '10,50');
assert.equal(pos.checkout.draft.receivedAmount, '');
assert.equal(pos.usdDraft.covered, '5302.5000');
assert.equal(pos.usdDraft.remaining, '2697.5000');
pos.updateCashReceived('USD', '');
assert.equal(pos.usdDraft.covered, '0.0000');
assert.equal(pos.usdDraft.remaining, '8000.0000');
assert.equal(pos.usdDraft.changeCrc, '0.0000');
assert.match(pos.money('58534.0000'), /58\s534,00/);
assert.match(pos.money('0.0000'), /0,00/);
assert.equal(pos.formatQuantity('440.0000'), '440,00');
assert.equal(pos.formatQuantity('4.1584'), '4,16');
assert.match(pos.usdPaymentLabel({ received_amount_usd: '440.0000', change_amount_usd: '0.0000' }), /US\$ 440,00.*US\$ 0,00/);
for (const expression of ['money(usdSession.rate)', 'money(usdDraft.equivalent)', 'money(usdDraft.covered)', 'money(usdDraft.remaining)', 'formatQuantity(usdDraft.changeUsd)', 'money(usdDraft?.changeCrc ?? 0)']) assert.ok(html.includes(expression), expression);
pos.checkout.draft = { methodId: cash.id, amount: '8000', receivedAmount: '0', receivedUsd: '20', reference: '' };
assert.equal(pos.usdCashEnabled, true);
assert.equal(pos.usdDraft.equivalent, '10100.0000');
assert.equal(pos.usdDraft.changeCrc, '2100.0000');
pos.usdSession.policy = 'usd_only';
assert.equal(pos.usdDraft.changeUsd, '4.1584');
pos.usdSession.policy = 'either';
assert.equal(pos.usdDraft.valid, false);
pos.checkout.draft.changeCurrency = 'USD';
assert.equal(pos.usdDraft.valid, true);
pos.checkout.draft.receivedUsd = 'NaN';
assert.equal(pos.usdDraft, null);
pos.checkout.draft.receivedUsd = '10';
pos.checkout.draft.receivedAmount = '2950';
assert.equal(pos.usdDraft, null, 'Conflicting stale inputs must never be summed');
assert.equal(pos.canAddPayment, false);
pos.updateCashReceived('USD', '20');
pos.addPayment();
assert.equal(pos.checkout.payments.length, 1);
assert.equal(pos.checkout.payments[0].received_amount, '0.0000');
assert.equal(pos.checkout.payments[0].received_amount_usd, '20.0000');
pos.usdSession.enabled = false;
assert.equal(pos.usdCashEnabled, false);
assert.equal(pos.paymentMethods.some(m => m.type === 'loyalty_points'), false);
assert.ok(pos.loyaltyBlockedReason.includes('Seleccione un cliente'));
pos.selectedCustomer = {id: 1};
Object.assign(pos.loyalty, {available: true, eligible: false, offers_allowed: true, max_redeemable_points: '100', requested: '50'});
assert.equal(pos.loyaltyRequestedPoints, 0);
assert.ok(pos.loyaltyBlockedReason.includes('mínimo'));
pos.loyalty.eligible = true;
pos.loyalty.offers_allowed = false;
assert.equal(pos.loyaltyRequestedPoints, 0);
assert.ok(pos.loyaltyBlockedReason.includes('ofertas'));
console.log('USD UI OK');
